// i2s_capture.sv -- capture-side wrapper around i2s_serdes, for use as a
// module reference inside a Vivado block design.
//
// Why this wrapper exists:
//   1. i2s_serdes outputs a 48-bit AXI-Stream (two 24-bit channels). The AXI DMA
//      only accepts 8/16/32/64/128-bit streams, so the frame is widened to 64
//      bits here, with each 24-bit sample sign extended to a 32-bit word. The PS
//      can then read the buffer directly as an array of int32 pairs.
//   2. i2s_serdes uses SystemVerilog interface ports (Axis_If), which Vivado
//      cannot infer as block design interfaces. This wrapper exposes flat
//      m_axis_* ports, which Vivado does infer.
//   3. The capture path needs no playback data, so the DAC stream is held idle.
//
// i2s_serdes and rising_edge/axis are reused from reed-foster/pynq-audio
// (MIT License, Copyright (c) 2020 Reed Foster); see hw/rtl/i2s/README-LICENSE.md.
//
// Clock domains: clk is the PL clock (100 MHz from FCLK_CLK0). bclk (3.072 MHz)
// and lrclk (48 kHz) are generated by the codec and cross into the clk domain
// through the synchronizers inside i2s_serdes.

module i2s_capture #(
    parameter int BIT_DEPTH = 24
) (
    input  wire        clk,
    input  wire        resetn,       // active low, from FCLK_RESET0_N
    input  wire        enabled,      // from axi_lite_ctrl reg0 bit0

    // I2S interface to the codec. The codec is the I2S master, so bclk and
    // lrclk are inputs here.
    input  wire        bclk,         // R18
    input  wire        lrclk,        // T17
    input  wire        sdata_i,      // F17, data from the codec ADC
    output wire        sdata_o,      // G18, data to the codec DAC (unused for now)

    // AXI4-Stream master: one 64-bit beat per I2S frame,
    // [63:32] = high half frame sign extended, [31:0] = low half frame.
    output wire [63:0] m_axis_tdata,
    output wire        m_axis_tvalid,
    input  wire        m_axis_tready
);

    Axis_If #(.DWIDTH(2*BIT_DEPTH)) dac_sample ();
    Axis_If #(.DWIDTH(2*BIT_DEPTH)) adc_sample ();

    // No playback data in the capture-only build: keep the DAC stream idle so
    // sdata_o stays low.
    assign dac_sample.valid = 1'b0;
    assign dac_sample.data  = '0;

    i2s_serdes #(.BIT_DEPTH(BIT_DEPTH)) u_serdes (
        .clk        (clk),
        .reset      (~resetn),
        .enabled    (enabled),
        .sdata_i    (sdata_i),
        .sdata_o    (sdata_o),
        .bclk       (bclk),
        .lrclk      (lrclk),
        .dac_sample (dac_sample),
        .adc_sample (adc_sample)
    );

    // Pure combinational widening: one 48-bit frame in, one 64-bit beat out.
    // Sign extension (not zero extension) keeps negative samples negative, so
    // the PS can view the buffer as plain int32 values.
    assign m_axis_tdata  = {{8{adc_sample.data[47]}}, adc_sample.data[47:24],
                            {8{adc_sample.data[23]}}, adc_sample.data[23:0]};
    assign m_axis_tvalid = adc_sample.valid;
    assign adc_sample.ready = m_axis_tready;

endmodule
